// Builds the Vite web app as ONE self-contained HTML file and embeds it as a TS module
// (mobile/webAppHtml.ts) so the Expo app in this folder runs the exact same UI fully offline.
// Run after any change under src/:  npm run sync-web
const {execSync} = require('child_process');
const fs = require('fs');
const path = require('path');

const os = require('os');

const root = path.resolve(__dirname, '..');

// The phone reaches the API over Wi-Fi, so bake in this computer's LAN address (override with VITE_API_URL).
const lanIp = Object.values(os.networkInterfaces()).flat().find((i) => i && i.family === 'IPv4' && !i.internal)?.address;
const apiUrl = process.env.VITE_API_URL ?? (lanIp ? `http://${lanIp}:${process.env.PORT || 4000}` : '');
console.log('API address baked into the phone build:', apiUrl || '(none: offline demo only)');

execSync('npx vite build --config vite.mobile.config.ts', {cwd: root, stdio: 'inherit', env: {...process.env, VITE_API_URL: apiUrl}});

const html = fs.readFileSync(path.join(root, 'dist-mobile/index.html'), 'utf8');
const out = path.join(root, 'mobile/webAppHtml.ts');
fs.mkdirSync(path.dirname(out), {recursive: true});
fs.writeFileSync(out, `// AUTO-GENERATED by scripts/sync-web.cjs. Do not edit.\nexport const WEB_APP_HTML = ${JSON.stringify(html)};\n`);
console.log('Wrote', out, (html.length / 1024).toFixed(0) + ' KB');
